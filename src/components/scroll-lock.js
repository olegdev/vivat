// Один замок прокрутки на все оверлеи сайта.
//
// Оверлеев у нас девять — модальные окна, бургер, меню каталога, поиск, ящик
// фильтров, шторка модулей, шторка раздела «Для бизнеса», выбор города и
// полноэкранная карта, — и каждый раньше гасил прокрутку сам: кто на `<html>`,
// кто на `<body>`. Два оверлея, открытых один над другим, при этом снимали
// замок друг у друга: закрылся верхний — страница поехала, хотя нижний ещё
// открыт. Поэтому замок общий и считает владельцев: страница стоит, пока
// открыт хоть один.
//
// Ключ — строка, своя у каждого оверлея. Повторный вызов с тем же значением
// ничего не меняет, поэтому `setScrollLock(key, open)` можно звать из того же
// места, что и `classList.toggle(..., open)`.
const holders = new Set();

export function setScrollLock(key, on) {
  if (on) holders.add(key);
  else holders.delete(key);

  const locked = holders.size > 0;
  // Оба узла: страница прокручивается то на одном, то на другом в зависимости
  // от того, что успел поставить браузер, и лишний класс ничего не ломает.
  document.documentElement.classList.toggle("overflow-hidden", locked);
  document.body.classList.toggle("overflow-hidden", locked);
}
